    @BeforeEach
    void schema() {
        // Demo startup and the admins fixture reuse account IDs across test contexts.
        jdbc.execute("TRUNCATE TABLE ogiri_sessions");
        jdbc.execute("TRUNCATE TABLE ogiri_subject_locks");
        jdbc.execute("DROP TABLE IF EXISTS admins");
        if ("mysql".equals(System.getenv("OGIRI_TEST_DATABASE")))
            jdbc.execute("CREATE TABLE admins LIKE users");
        else {
            jdbc.execute("CREATE TABLE admins (LIKE users INCLUDING ALL)");
            jdbc.execute("ALTER TABLE admins ALTER COLUMN id DROP DEFAULT");
            jdbc.execute("ALTER TABLE admins ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY");
        }
    }

    @AfterEach
    void removeOwnedAccountTable() {
        jdbc.execute("DROP TABLE IF EXISTS admins");
    }

    @Test
    void removedCurrentCredentialExpiresOnlyItsRealmCookieForJsonAndFormMutations()
            throws Exception {
        for (String suffix : List.of("", "/password")) {
            for (boolean form : new boolean[] {false, true}) {
                var sessions = pair("/auth");
                String name = realms.defaultRealm().settings().cookieName();
                String oldCookie = cookie(sessions.older(), name);
                String newestCookie = cookie(sessions.newest(), name);
                var headers = cookieHeaders("/auth", oldCookie);
                headers.put("Cookie", headers.get("Cookie") + "; admin_auth_cookie=unrelated");
                var changed = mutation("/auth" + suffix, password(), headers, form);
                assertSuccess(changed, suffix);
                assertCleared(changed);
                assertNoResponseCredentials(changed);
                assertEquals(401, validate("/auth", Map.of("Cookie", oldCookie)).statusCode());
                var retained = validate("/auth", Map.of("Cookie", newestCookie));
                assertEquals(200, retained.statusCode(), retained.body());
            }
        }
    }

    @Test
    void retainedCurrentCredentialRemainsUsableWithoutCookieDeletionForJsonAndFormMutations()
            throws Exception {
        for (String suffix : List.of("", "/password")) {
            for (boolean form : new boolean[] {false, true}) {
                var sessions = pair("/auth");
                String name = realms.defaultRealm().settings().cookieName();
                var changed =
                        mutation(
                                "/auth" + suffix,
                                password(),
                                cookieHeaders("/auth", cookie(sessions.newest(), name)),
                                form);
                assertSuccess(changed, suffix);
                var cookies = authCookies(changed);
                assertEquals(1, cookies.size(), changed.headers().toString());
                assertFalse(cookies.get(0).contains("Max-Age=0"), cookies.get(0));
                assertEquals(
                        sessions.newest().headers().firstValue("client"),
                        changed.headers().firstValue("client"));
                var retained = validate("/auth", Map.of("Cookie", cookie(changed, name)));
                assertEquals(200, retained.statusCode(), retained.body());
                assertEquals(
                        401,
                        validate("/auth", Map.of("Cookie", cookie(sessions.older(), name)))
                                .statusCode());
            }
        }
    }

    @Test
    void cookieDisabledHeaderClientsReceiveNoDeletionAndFollowTheSameRetentionPolicy()
            throws Exception {
        for (String suffix : List.of("", "/password")) {
            for (boolean form : new boolean[] {false, true}) {
                for (boolean retainCurrent : new boolean[] {false, true}) {
                    var sessions = pair("/admin_auth");
                    var headers =
                            credentialHeaders(retainCurrent ? sessions.newest() : sessions.older());
                    // Even a presented auth cookie cannot enable cookie output for this realm.
                    headers.put("Cookie", "admin_auth_cookie=unrelated");
                    var changed = mutation("/admin_auth" + suffix, password(), headers, form);
                    assertSuccess(changed, suffix);
                    assertTrue(authCookies(changed).isEmpty(), changed.headers().toString());
                    if (!retainCurrent) assertNoResponseCredentials(changed);
                    var retained =
                            validate(
                                    "/admin_auth",
                                    credentialHeaders(retainCurrent ? changed : sessions.newest()));
                    assertEquals(200, retained.statusCode(), retained.body());
                    assertEquals(
                            401,
                            validate("/admin_auth", credentialHeaders(sessions.older()))
                                    .statusCode());
                }
            }
        }
    }

    @Test
    void authenticatedTokenResetForAnotherAccountPreservesUsableCallerCredentials()
            throws Exception {
        for (boolean form : new boolean[] {false, true}) {
            var authenticated = pair("/auth");
            var target = pair("/auth");
            var runtime = realms.defaultRealm();
            String name = runtime.settings().cookieName();
            var accountA = runtime.accounts().findByUid(authenticated.email()).orElseThrow();
            var accountB = runtime.accounts().findByUid(target.email()).orElseThrow();
            var subjectA = runtime.settings().subject(accountA);
            var subjectB = runtime.settings().subject(accountB);
            var sessionsA = runtime.sessions().list(subjectA);
            assertEquals(2, sessionsA.size());
            String clientA = authenticated.older().headers().firstValue("client").orElseThrow();
            String sessionA =
                    sessionsA.stream()
                            .filter(session -> session.client().equals(clientA))
                            .findFirst()
                            .orElseThrow()
                            .id()
                            .toString();
            byte[] originalHash =
                    jdbc.queryForObject(
                            "SELECT token_hash FROM ogiri_sessions WHERE id = ?",
                            byte[].class,
                            sessionA);
            var body = new HashMap<>(password());
            body.put("reset_password_token", resetToken(target.email()));
            String originalCookie = cookie(authenticated.older(), name);
            var changed =
                    mutation("/auth/password", body, cookieHeaders("/auth", originalCookie), form);
            assertSuccess(changed, "/password");
            var data = (Map<?, ?>) json.readValue(changed.body(), Map.class).get("data");
            assertEquals(target.email(), data.get("email"));
            var returnedCookies = authCookies(changed);
            assertEquals(1, returnedCookies.size(), changed.headers().toString());
            assertFalse(returnedCookies.get(0).contains("Max-Age=0"), returnedCookies.get(0));
            assertEquals(authenticated.email(), changed.headers().firstValue("uid").orElseThrow());
            assertEquals(clientA, changed.headers().firstValue("client").orElseThrow());
            assertEquals(
                    accountA.getPassword(),
                    runtime.accounts()
                            .findByUid(authenticated.email())
                            .orElseThrow()
                            .getPassword());
            var updatedB = runtime.accounts().findByUid(target.email()).orElseThrow();
            assertNotEquals(accountB.getPassword(), updatedB.getPassword());
            assertNull(updatedB.column("reset_password_token"));
            assertEquals(
                    List.of(target.newest().headers().firstValue("client").orElseThrow()),
                    runtime.sessions().list(subjectB).stream()
                            .map(com.quantipixels.ogiri.Session::client)
                            .toList());
            assertEquals(
                    sessionsA.stream().map(com.quantipixels.ogiri.Session::id).toList(),
                    runtime.sessions().list(subjectA).stream()
                            .map(com.quantipixels.ogiri.Session::id)
                            .toList());
            // Authentication rotates A normally; B's reset must deliver A's replacement.
            // Age the batch window so a previous token cannot masquerade as preservation.
            assertArrayEquals(
                    originalHash,
                    jdbc.queryForObject(
                            "SELECT previous_token_hash FROM ogiri_sessions WHERE id = ?",
                            byte[].class,
                            sessionA));
            assertFalse(
                    java.util.Arrays.equals(
                            originalHash,
                            jdbc.queryForObject(
                                    "SELECT token_hash FROM ogiri_sessions WHERE id = ?",
                                    byte[].class,
                                    sessionA)));
            assertEquals(
                    1,
                    jdbc.update("UPDATE ogiri_sessions SET rotated_at = 0 WHERE id = ?", sessionA));
            assertEquals(401, validate("/auth", Map.of("Cookie", originalCookie)).statusCode());
            var caller = validate("/auth", Map.of("Cookie", cookie(changed, name)));
            assertEquals(200, caller.statusCode(), caller.body());
            var callerData = (Map<?, ?>) json.readValue(caller.body(), Map.class).get("data");
            assertEquals(authenticated.email(), callerData.get("email"));
            assertEquals(
                    sessionsA.stream().map(com.quantipixels.ogiri.Session::id).toList(),
                    runtime.sessions().list(subjectA).stream()
                            .map(com.quantipixels.ogiri.Session::id)
                            .toList());
            assertEquals(
                    401,
                    validate("/auth", Map.of("Cookie", cookie(target.older(), name))).statusCode());
            var retained = validate("/auth", Map.of("Cookie", cookie(target.newest(), name)));
            assertEquals(200, retained.statusCode(), retained.body());
        }
    }

    @Test
    void unauthenticatedTokenResetWithForeignCookieDoesNotClearAnAuthenticatedSessionCookie()
            throws Exception {
        for (boolean form : new boolean[] {false, true}) {
            var sessions = pair("/auth");
            var foreign = pair("/admin_auth");
            var body = new HashMap<>(password());
            body.put("reset_password_token", resetToken(sessions.email()));
            String foreignCookie =
                    "admin_auth_cookie="
                            + URLEncoder.encode(
                                    json.writeValueAsString(credentialHeaders(foreign.newest())),
                                    StandardCharsets.UTF_8);
            var changed = mutation("/auth/password", body, Map.of("Cookie", foreignCookie), form);
            assertSuccess(changed, "/password");
            assertTrue(authCookies(changed).isEmpty(), changed.headers().toString());
            assertNoResponseCredentials(changed);
            String name = realms.defaultRealm().settings().cookieName();
            assertEquals(
                    401,
                    validate("/auth", Map.of("Cookie", cookie(sessions.older(), name)))
                            .statusCode());
            var retained = validate("/auth", Map.of("Cookie", cookie(sessions.newest(), name)));
            assertEquals(200, retained.statusCode(), retained.body());
            var unrelated = validate("/admin_auth", credentialHeaders(foreign.newest()));
            assertEquals(200, unrelated.statusCode(), unrelated.body());
        }
    }

    private String resetToken(String email) throws Exception {
        byte[] tokenBytes = new byte[32];
        new java.security.SecureRandom().nextBytes(tokenBytes);
        String token = java.util.Base64.getUrlEncoder().withoutPadding().encodeToString(tokenBytes);
        String digest =
                java.util.HexFormat.of()
                        .formatHex(
                                java.security.MessageDigest.getInstance("SHA-256")
                                        .digest(token.getBytes(StandardCharsets.US_ASCII)));
        long now = realms.defaultRealm().transactions().now();
        assertEquals(
                1,
                jdbc.update(
                        "UPDATE users SET reset_password_token = ?, reset_password_sent_at = ? WHERE email = ?",
                        digest,
                        java.sql.Timestamp.from(java.time.Instant.ofEpochMilli(now)),
                        email));
        return token;
    }

    private record Pair(String email, HttpResponse<String> older, HttpResponse<String> newest) {}

    private Pair pair(String path) throws Exception {
        String email = "cookie-lifecycle-" + UUID.randomUUID() + "@example.com";
        Map<String, String> headers = path.equals("/auth") ? cookieHeaders(path, null) : Map.of();
        var older =
                request(
                        "POST",
                        path,
                        Map.of(
                                "email",
                                email,
                                "password",
                                "test-password",
                                "password_confirmation",
                                "test-password"),
                        headers,
                        false);
        assertEquals(200, older.statusCode(), older.body());
        var newest =
                request(
                        "POST",
                        path + "/sign_in",
                        Map.of("email", email, "password", "test-password"),
                        headers,
                        false);
        assertEquals(200, newest.statusCode(), newest.body());
        String oldClient = older.headers().firstValue("client").orElseThrow();
        String newClient = newest.headers().firstValue("client").orElseThrow();
        assertNotEquals(oldClient, newClient);
        // DB-clock ordering selects the newer session deterministically without sleeping.
        // Force a non-batch authentication so a missing clear would emit fresh credentials.
        long now = realms.defaultRealm().transactions().now();
        assertEquals(
                1,
                jdbc.update(
                        "UPDATE ogiri_sessions SET created_at = ?, rotated_at = 0 WHERE client = ?",
                        now - 1,
                        oldClient));
        assertEquals(
                1,
                jdbc.update(
                        "UPDATE ogiri_sessions SET created_at = ?, rotated_at = 0 WHERE client = ?",
                        now,
                        newClient));
        return new Pair(email, older, newest);
    }

    private Map<String, String> cookieHeaders(String path, String auth) throws Exception {
        String csrf =
                cookie(request("GET", path + "/sign_in", null, Map.of(), false), "XSRF-TOKEN");
        return new HashMap<>(
                Map.of(
                        "Cookie",
                        auth == null ? csrf : auth + "; " + csrf,
                        "X-XSRF-TOKEN",
                        csrf.substring(csrf.indexOf('=') + 1)));
    }

    private static Map<String, String> password() {
        return Map.of(
                "password",
                "changed-password",
                "password_confirmation",
                "changed-password",
                "current_password",
                "test-password");
    }

    private void assertSuccess(HttpResponse<String> response, String suffix) {
        assertEquals(200, response.statusCode(), response.body());
        var body = json.readValue(response.body(), Map.class);
        if (suffix.equals("/password")) assertEquals(true, body.get("success"));
        else assertEquals("success", body.get("status"));
    }

    private void assertCleared(HttpResponse<String> response) {
        var cookies = authCookies(response);
        assertEquals(1, cookies.size(), response.headers().toString());
        String cleared = cookies.get(0);
        var settings = realms.defaultRealm().settings();
        assertEquals(settings.cookieName() + "=", cleared.split(";", 2)[0]);
        var attributes = List.of(cleared.split(";\\s*"));
        assertTrue(attributes.contains("Max-Age=0"), cleared);
        assertTrue(attributes.contains("Path=" + settings.cookiePath()), cleared);
        assertTrue(attributes.contains("HttpOnly"), cleared);
        assertTrue(attributes.contains("Secure"), cleared);
        assertTrue(attributes.contains("SameSite=" + settings.cookieSameSite()), cleared);
    }

    private List<String> authCookies(HttpResponse<String> response) {
        return response.headers().allValues("Set-Cookie").stream()
                .filter(
                        cookie ->
                                cookie.startsWith(
                                                realms.defaultRealm().settings().cookieName() + "=")
                                        || cookie.startsWith(
                                                realms.additional().get(0).settings().cookieName()
                                                        + "="))
                .toList();
    }

    private static void assertNoResponseCredentials(HttpResponse<String> response) {
        for (String name :
                List.of("access-token", "client", "uid", "expiry", "token-type", "Authorization"))
            assertFalse(response.headers().firstValue(name).isPresent(), name);
    }

    private static Map<String, String> credentialHeaders(HttpResponse<String> response) {
        var fields = new HashMap<String, String>();
        for (String name : List.of("access-token", "client", "uid"))
            fields.put(name, response.headers().firstValue(name).orElseThrow());
        return fields;
    }

    private static String cookie(HttpResponse<String> response, String name) {
        return response.headers().allValues("Set-Cookie").stream()
                .filter(cookie -> cookie.startsWith(name + "="))
                .findFirst()
                .orElseThrow()
                .split(";", 2)[0];
    }

    private HttpResponse<String> validate(String path, Map<String, String> headers)
            throws Exception {
        return request("GET", path + "/validate_token", null, headers, false);
    }

    private HttpResponse<String> mutation(
            String path, Map<String, String> body, Map<String, String> headers, boolean form)
            throws Exception {
        return request(form ? "PATCH" : "PUT", path, body, headers, form);
    }

    private HttpResponse<String> request(
            String method,
            String path,
            Map<String, String> body,
            Map<String, String> headers,
            boolean form)
            throws Exception {
        // Explicit Cookie headers exercise Secure attributes over the local RANDOM_PORT server.
        var builder =
                HttpRequest.newBuilder(URI.create("http://127.0.0.1:" + port + path))
                        .timeout(Duration.ofSeconds(10))
                        .header(
                                "Content-Type",
                                form ? "application/x-www-form-urlencoded" : "application/json");
        headers.forEach(builder::header);
        String encoded =
                body == null
                        ? null
                        : form
                                ? body.entrySet().stream()
                                        .map(
                                                entry ->
                                                        URLEncoder.encode(
                                                                        entry.getKey(),
                                                                        StandardCharsets.UTF_8)
                                                                + "="
                                                                + URLEncoder.encode(
                                                                        entry.getValue(),
                                                                        StandardCharsets.UTF_8))
                                        .collect(java.util.stream.Collectors.joining("&"))
                                : json.writeValueAsString(body);
        builder.method(
                method,
                encoded == null
                        ? HttpRequest.BodyPublishers.noBody()
                        : HttpRequest.BodyPublishers.ofString(encoded, StandardCharsets.UTF_8));
        return http.send(builder.build(), HttpResponse.BodyHandlers.ofString());
    }
