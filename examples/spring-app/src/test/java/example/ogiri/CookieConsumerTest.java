package example.ogiri;

import static org.junit.jupiter.api.Assertions.*;

import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.charset.StandardCharsets;
import java.util.Base64;
import java.util.Map;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import tools.jackson.databind.json.JsonMapper;

@SpringBootTest(
        classes = {Application.class, HostChainTest.Host.class},
        webEnvironment = SpringBootTest.WebEnvironment.RANDOM_PORT,
        properties = {
            "spring.datasource.url=${OGIRI_TEST_JDBC_URL}",
            "spring.datasource.username=${OGIRI_TEST_JDBC_USER}",
            "spring.datasource.password=${OGIRI_TEST_JDBC_PASSWORD}",
            "spring.datasource.hikari.maximum-pool-size=1",
            "spring.profiles.active=demo",
            "ogiri.cookie-enabled=true",
            "ogiri.cookie-secure=false"
        })
class CookieConsumerTest {
    @Value("${local.server.port}")
    int port;

    @Autowired JdbcTemplate jdbc;
    private final HttpClient http = HttpClient.newHttpClient();
    private final JsonMapper json = JsonMapper.builder().build();

    @BeforeEach
    void schema() {
        jdbc.execute("DROP TABLE IF EXISTS admins");
        if ("mysql".equals(System.getenv("OGIRI_TEST_DATABASE")))
            jdbc.execute("CREATE TABLE admins LIKE users");
        else {
            jdbc.execute("CREATE TABLE admins (LIKE users INCLUDING ALL)");
            jdbc.execute("ALTER TABLE admins ALTER COLUMN id DROP DEFAULT");
            jdbc.execute("ALTER TABLE admins ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY");
        }
    }

    @AfterEach
    void removeOwnedAccountTable() {
        jdbc.execute("DROP TABLE IF EXISTS admins");
    }

    @Test
    void loginCsrfRequiresCookieAndEchoBeforeCreatingAnySession() throws Exception {
        var bootstrap = request("GET", "/auth/sign_in", null, Map.of());
        String csrf = cookie(bootstrap, "XSRF-TOKEN");
        var body = Map.of("email", "demo@example.com", "password", "test-password");
        int before = jdbc.queryForObject("SELECT COUNT(*) FROM ogiri_sessions", Integer.class);
        for (var headers :
                java.util.List.of(
                        Map.<String, String>of(),
                        Map.of("Cookie", csrf),
                        Map.of("X-XSRF-TOKEN", value(csrf)),
                        Map.of("Cookie", csrf, "X-XSRF-TOKEN", "wrong"))) {
            var rejected = request("POST", "/auth/sign_in", body, headers);
            assertEquals(403, rejected.statusCode(), rejected.body());
            assertEquals(
                    Map.of("success", false, "errors", java.util.List.of("Invalid CSRF token")),
                    json.readValue(rejected.body(), Map.class));
        }
        assertEquals(
                before, jdbc.queryForObject("SELECT COUNT(*) FROM ogiri_sessions", Integer.class));
        var accepted =
                request(
                        "POST",
                        "/auth/sign_in",
                        body,
                        Map.of(
                                "Cookie",
                                csrf + "; auth_cookie=stale",
                                "X-XSRF-TOKEN",
                                value(csrf)));
        assertEquals(200, accepted.statusCode(), accepted.body());
        assertTrue(cookie(accepted, "auth_cookie").startsWith("auth_cookie="));
        assertFalse(accepted.headers().firstValue("Authorization").isPresent());
    }

    @Test
    void cookieUnsafeRequestsRejectMissingWrongAndMalformedHeaderBypasses() throws Exception {
        var issued = signup("/auth");
        String auth = cookie(issued, "auth_cookie");
        String csrf = cookie(issued, "XSRF-TOKEN");
        String cookies = auth + "; " + csrf;
        for (var extra :
                java.util.List.of(
                        Map.<String, String>of(),
                        Map.of("X-XSRF-TOKEN", "wrong"),
                        Map.of("Authorization", "Bearer !!!"),
                        Map.of(
                                "Authorization",
                                bearer(
                                        Map.of(
                                                "access-token",
                                                42,
                                                "uid",
                                                false,
                                                "client",
                                                java.util.List.of()))),
                        Map.of("uid", issued.headers().firstValue("uid").orElseThrow()))) {
            var headers = new java.util.HashMap<>(extra);
            headers.put("Cookie", cookies);
            var rejected = request("DELETE", "/auth/sign_out", null, headers);
            assertEquals(403, rejected.statusCode(), rejected.body());
            assertEquals(200, request("GET", "/me", null, Map.of("Cookie", auth)).statusCode());
        }
        var signedOut =
                request(
                        "DELETE",
                        "/auth/sign_out",
                        null,
                        Map.of("Cookie", cookies, "X-XSRF-TOKEN", value(csrf)));
        assertEquals(200, signedOut.statusCode(), signedOut.body());
        assertCleared(signedOut, "auth_cookie");
        assertEquals(401, request("GET", "/me", null, Map.of("Cookie", auth)).statusCode());
    }

    @Test
    void completeHeaderAndBearerCredentialsNeverRequireCookieCsrf() throws Exception {
        for (boolean bearer : new boolean[] {false, true}) {
            var issued = signup("/auth");
            var fields = new java.util.HashMap<String, String>();
            for (String key : java.util.List.of("access-token", "client", "uid"))
                fields.put(key, issued.headers().firstValue(key).orElseThrow());
            var headers =
                    new java.util.HashMap<>(
                            bearer ? Map.of("Authorization", bearer(fields)) : fields);
            headers.put("Cookie", cookie(issued, "auth_cookie"));
            var response = request("DELETE", "/auth/sign_out", null, headers);
            assertEquals(200, response.statusCode(), response.body());
            assertCleared(response, "auth_cookie");
        }
    }

    @Test
    void publicWorkflowsIgnoreInvalidCookiesAndRealmCookiesNeverCrossStores() throws Exception {
        var user = signup("/auth");
        var admin = signup("/admin_auth");
        String users = cookie(user, "auth_cookie");
        String admins = cookie(admin, "admin_auth_cookie");
        assertEquals(
                200,
                request("GET", "/admin_auth/validate_token", null, Map.of("Cookie", admins))
                        .statusCode());
        for (String foreign :
                java.util.List.of(
                        users, users.replaceFirst("auth_cookie=", "admin_auth_cookie="))) {
            assertEquals(
                    401,
                    request("GET", "/admin_auth/validate_token", null, Map.of("Cookie", foreign))
                            .statusCode());
        }
        assertEquals(
                401,
                request("GET", "/auth/validate_token", null, Map.of("Cookie", admins))
                        .statusCode());
        var publicResponse =
                request(
                        "POST",
                        "/auth/password",
                        Map.of(
                                "email",
                                "missing@example.com",
                                "redirect_url",
                                "https://client.example.test/reset"),
                        Map.of("Cookie", "auth_cookie=invalid"));
        var anonymous =
                request(
                        "POST",
                        "/auth/password",
                        Map.of(
                                "email",
                                "missing@example.com",
                                "redirect_url",
                                "https://client.example.test/reset"),
                        Map.of());
        assertEquals(404, publicResponse.statusCode(), publicResponse.body());
        assertEquals(anonymous.statusCode(), publicResponse.statusCode());
        assertEquals(anonymous.body(), publicResponse.body());
        assertEquals(
                200,
                request("GET", "/auth/validate_token", null, Map.of("Cookie", users)).statusCode());
    }

    @Test
    void currentDeviceAllDevicesAndAccountDeletionClearCookieAndResponseCredentials()
            throws Exception {
        for (String target : java.util.List.of("/auth/sessions/", "/auth/sessions", "/auth")) {
            var issued = signup("/auth");
            String auth = cookie(issued, "auth_cookie");
            String csrf = cookie(issued, "XSRF-TOKEN");
            String path =
                    target.endsWith("/")
                            ? target + issued.headers().firstValue("client").orElseThrow()
                            : target;
            var response =
                    request(
                            "DELETE",
                            path,
                            null,
                            Map.of("Cookie", auth + "; " + csrf, "X-XSRF-TOKEN", value(csrf)));
            assertEquals(200, response.statusCode(), response.body());
            assertCleared(response, "auth_cookie");
            assertEquals(401, request("GET", "/me", null, Map.of("Cookie", auth)).statusCode());
        }
    }

    private void assertCleared(HttpResponse<String> response, String name) {
        String cleared =
                response.headers().allValues("Set-Cookie").stream()
                        .filter(c -> c.startsWith(name + "="))
                        .findFirst()
                        .orElseThrow();
        assertTrue(cleared.contains("Max-Age=0"), cleared);
        for (String header :
                java.util.List.of(
                        "access-token", "client", "uid", "expiry", "token-type", "Authorization"))
            assertFalse(response.headers().firstValue(header).isPresent(), header);
    }

    private HttpResponse<String> signup(String path) throws Exception {
        var response =
                request(
                        "POST",
                        path,
                        Map.of(
                                "email",
                                "cookie-" + java.util.UUID.randomUUID() + "@example.com",
                                "password",
                                "test-password",
                                "password_confirmation",
                                "test-password"),
                        Map.of("Cookie", "auth_cookie=stale; admin_auth_cookie=stale"));
        assertEquals(200, response.statusCode(), response.body());
        return response;
    }

    private static String cookie(HttpResponse<String> response, String name) {
        return response.headers().allValues("Set-Cookie").stream()
                .filter(c -> c.startsWith(name + "="))
                .findFirst()
                .orElseThrow()
                .split(";", 2)[0];
    }

    private static String value(String cookie) {
        return cookie.substring(cookie.indexOf('=') + 1);
    }

    private String bearer(Map<String, ?> fields) {
        return "Bearer " + Base64.getEncoder().encodeToString(json.writeValueAsBytes(fields));
    }

    private HttpResponse<String> request(
            String method, String path, Map<String, String> body, Map<String, String> headers)
            throws Exception {
        var builder =
                HttpRequest.newBuilder(URI.create("http://127.0.0.1:" + port + path))
                        .header("Content-Type", "application/json");
        headers.forEach(builder::header);
        builder.method(
                method,
                body == null
                        ? HttpRequest.BodyPublishers.noBody()
                        : HttpRequest.BodyPublishers.ofString(
                                json.writeValueAsString(body), StandardCharsets.UTF_8));
        return http.send(builder.build(), HttpResponse.BodyHandlers.ofString());
    }
}
